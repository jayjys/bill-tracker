-- Kept to SQL that runs on both PostgreSQL and H2 (PostgreSQL mode) so the
-- same migrations back production, local dev, and fast tests.

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    display_name   VARCHAR(100),
    inbound_token  VARCHAR(32)  NOT NULL UNIQUE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE bill (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    provider          VARCHAR(120),
    utility_type      VARCHAR(20)   NOT NULL,
    amount            NUMERIC(12, 2),
    due_date          DATE,
    period_start      DATE,
    period_end        DATE,
    usage_quantity    NUMERIC(14, 3),
    usage_unit        VARCHAR(20),
    account_last4     VARCHAR(4),
    source            VARCHAR(20)   NOT NULL,
    original_filename VARCHAR(255),
    content_sha256    VARCHAR(64),
    raw_text          TEXT,
    parse_confidence  NUMERIC(4, 3) NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_bill_user_period ON bill (user_id, period_end);
CREATE UNIQUE INDEX uq_bill_user_sha ON bill (user_id, content_sha256);
