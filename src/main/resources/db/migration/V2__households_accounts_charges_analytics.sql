-- V2: normalise the model around households and utility accounts, add line-item
-- charges, analytics tables (weather, alerts) and a job log. Existing data is
-- backfilled so nothing is lost. Portable between PostgreSQL and H2 (PG mode).

-- ---------------------------------------------------------------- households
CREATE TABLE household (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    occupants   INT          NOT NULL DEFAULT 1 CHECK (occupants BETWEEN 1 AND 20),
    city        VARCHAR(120),
    latitude    NUMERIC(8, 5),
    longitude   NUMERIC(8, 5),
    invite_code VARCHAR(32) UNIQUE,
    owner_id    BIGINT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Every existing user gets their own household.
INSERT INTO household (name, occupants, owner_id, created_at)
SELECT 'Home', 1, id, created_at FROM app_user;

ALTER TABLE app_user ADD COLUMN household_id BIGINT;
UPDATE app_user SET household_id = (SELECT h.id FROM household h WHERE h.owner_id = app_user.id);
ALTER TABLE app_user ALTER COLUMN household_id SET NOT NULL;
ALTER TABLE app_user ADD CONSTRAINT fk_user_household FOREIGN KEY (household_id) REFERENCES household (id);
ALTER TABLE household ADD CONSTRAINT fk_household_owner FOREIGN KEY (owner_id) REFERENCES app_user (id) ON DELETE SET NULL;

-- ---------------------------------------------------------- utility accounts
-- One row per (household, provider, utility, account number). A combined
-- electric + gas statement belongs to two accounts.
CREATE TABLE utility_account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id  BIGINT       NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    provider      VARCHAR(120) NOT NULL,
    utility_type  VARCHAR(20)  NOT NULL,
    account_last4 VARCHAR(4)   NOT NULL DEFAULT '',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_utility_account UNIQUE (household_id, provider, utility_type, account_last4)
);

-- ---------------------------------------------------------------------- bills
ALTER TABLE bill ADD COLUMN household_id BIGINT;
ALTER TABLE bill ADD COLUMN utility_account_id BIGINT;
ALTER TABLE bill ADD COLUMN service_days INT;
ALTER TABLE bill ADD COLUMN parser_version INT NOT NULL DEFAULT 1;
ALTER TABLE bill ADD COLUMN parse_warnings VARCHAR(1000);

UPDATE bill SET household_id = (SELECT u.household_id FROM app_user u WHERE u.id = bill.user_id);

INSERT INTO utility_account (household_id, provider, utility_type, account_last4, created_at)
SELECT DISTINCT b.household_id, COALESCE(b.provider, 'Unknown'), b.utility_type, COALESCE(b.account_last4, ''),
       CURRENT_TIMESTAMP
FROM bill b;

UPDATE bill SET utility_account_id = (
    SELECT a.id FROM utility_account a
    WHERE a.household_id = bill.household_id
      AND a.provider = COALESCE(bill.provider, 'Unknown')
      AND a.utility_type = bill.utility_type
      AND a.account_last4 = COALESCE(bill.account_last4, ''));

ALTER TABLE bill ALTER COLUMN household_id SET NOT NULL;
ALTER TABLE bill ALTER COLUMN utility_account_id SET NOT NULL;
ALTER TABLE bill ADD CONSTRAINT fk_bill_household FOREIGN KEY (household_id) REFERENCES household (id) ON DELETE CASCADE;
ALTER TABLE bill ADD CONSTRAINT fk_bill_account FOREIGN KEY (utility_account_id) REFERENCES utility_account (id);

-- Provider, utility and account number now live on utility_account.
DROP INDEX uq_bill_user_sha;
ALTER TABLE bill DROP COLUMN provider;
ALTER TABLE bill DROP COLUMN utility_type;
ALTER TABLE bill DROP COLUMN account_last4;

-- The same file can hold several bills (one per utility section), but never twice for one account.
CREATE UNIQUE INDEX uq_bill_source ON bill (household_id, content_sha256, utility_account_id);
CREATE INDEX idx_bill_household_period ON bill (household_id, period_end);
CREATE INDEX idx_bill_account_period ON bill (utility_account_id, period_end);

-- ------------------------------------------------------------ line-item charges
CREATE TABLE bill_charge (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id     BIGINT        NOT NULL REFERENCES bill (id) ON DELETE CASCADE,
    line_no     INT           NOT NULL,
    description VARCHAR(200)  NOT NULL,
    category    VARCHAR(20)   NOT NULL,
    amount      NUMERIC(12, 2) NOT NULL
);
CREATE INDEX idx_charge_bill ON bill_charge (bill_id);

-- ---------------------------------------------------------------- analytics
-- Daily mean temperature per location (lat/lon rounded to 0.1°, ~10 km).
CREATE TABLE weather_day (
    location_key VARCHAR(20)  NOT NULL,
    obs_date     DATE         NOT NULL,
    temp_mean_c  NUMERIC(5, 2) NOT NULL,
    PRIMARY KEY (location_key, obs_date)
);

CREATE TABLE alert (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id BIGINT       NOT NULL REFERENCES household (id) ON DELETE CASCADE,
    bill_id      BIGINT       NOT NULL REFERENCES bill (id) ON DELETE CASCADE,
    kind         VARCHAR(30)  NOT NULL,
    severity     VARCHAR(10)  NOT NULL,
    title        VARCHAR(200) NOT NULL,
    detail       VARCHAR(1000),
    observed     NUMERIC(14, 4),
    expected     NUMERIC(14, 4),
    score        NUMERIC(8, 3),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    dismissed_at TIMESTAMP WITH TIME ZONE
);
-- Detection is re-run nightly; one alert per bill and kind keeps it idempotent.
CREATE UNIQUE INDEX uq_alert_bill_kind ON alert (bill_id, kind);
CREATE INDEX idx_alert_household ON alert (household_id, created_at);

-- ---------------------------------------------------------------- job log
CREATE TABLE job_run (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name    VARCHAR(60)  NOT NULL,
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE,
    status      VARCHAR(10)  NOT NULL,
    items       INT,
    message     VARCHAR(1000)
);
CREATE INDEX idx_job_run_name ON job_run (job_name, started_at);
